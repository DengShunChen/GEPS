      con = (daynum-numd(j)) / (numd(j+1)-numd(j))
      do 70 i = 1,16*12
      if ( (con.gt.0.0) .and. (con.le.1.0) )   &
         o3wk(i,1) = (tabo3(i,1,j) + con*(tabo3(i,1,j+1)-tabo3(i,1,j))) * fac
   70 continue
   90 continue
!
      else
!
      con = (daynum-numd(12)) / (380.-numd(12))
      do 100 i = 1,16*12
      o3wk(i,1) = (tabo3(i,1,12) + con*(tabo3(i,1,1)-tabo3(i,1,12))) * fac
  100 continue
      endif
!
!  linearly interpolate for altitude
!
      if ( (theta.le.aref(1)) .or. (theta.ge.aref(16)) ) then
      do 200 k = 1,12
      if ( theta .le. aref(1) )  o3z(k) = o3wk(1,k)
      if ( theta .ge. aref(16) ) o3z(k) = o3wk(16,k)
  200 continue
!
      else
!
      ll  = (theta+75.)/10.0 + 1
      con = (theta-aref(ll)) / (aref(ll+1)-aref(ll))
      do 220 k = 1,12
      o3z(k) = o3wk(ll,k) + con*(o3wk(ll+1,k)-o3wk(ll,k))
  220 continue
      endif
!
!  linear interpolate for p
!
      do 300 k = 1, lm
      do 300 i = 1, nxj
      if ( pp(i,k) .le. pref(1) )  o3l(i,k) = o3z(1)
      if ( pp(i,k) .ge. pref(12) ) o3l(i,k) = o3z(12)
  300 continue
!
      do 390 k = 1,11
      do 310 kk = 1, lm
      do 310 i = 1, nxj
      con = (pp(i,kk)-pref(k)) / (pref(k+1)-pref(k))
      if ( (con.gt.0.0) .and. (con.le.1.0) ) &
          o3l(i,kk) = o3z(k) + con*(o3z(k+1)-o3z(k))
 310  continue
 390  continue
!
      return
      end
